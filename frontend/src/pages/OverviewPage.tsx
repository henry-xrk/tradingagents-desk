import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { useState, type FormEvent } from "react";
import { Link, useNavigate } from "react-router-dom";

import { Panel } from "../components/AgentWorkflow.tsx";
import { Badge } from "../components/ui/badge.tsx";
import { Button } from "../components/ui/button.tsx";
import { Input } from "../components/ui/input.tsx";
import { formatNumber, formatWhen } from "../lib/utils.ts";
import { api } from "../services/api.ts";
import type { AnalysisRecord, ConfigOptions, WatchlistResponse } from "../types/api.ts";

const ACTIVE = new Set(["queued", "running", "cancel_requested", "cancelling"]);

export function OverviewPage() {
  const navigate = useNavigate();
  const queryClient = useQueryClient();
  const [ticker, setTicker] = useState("");
  const auth = useQuery({ queryKey: ["options"], queryFn: () => api<ConfigOptions>("/api/config/options") });
  const watchlist = useQuery({ queryKey: ["watchlist"], queryFn: () => api<WatchlistResponse>("/api/watchlist") });
  const active = useQuery({
    queryKey: ["analyses", "active"],
    queryFn: () => api<AnalysisRecord[]>("/api/analyses/active"),
    refetchInterval: 5000,
  });
  const history = useQuery({
    queryKey: ["analyses"],
    queryFn: () => api<AnalysisRecord[]>("/api/history?limit=12"),
  });
  const add = useMutation({
    mutationFn: (symbol: string) => api<{ ticker: string }>("/api/watchlist", { method: "POST", body: JSON.stringify({ ticker: symbol }) }),
    onSuccess: async () => {
      setTicker("");
      await queryClient.invalidateQueries({ queryKey: ["watchlist"] });
    },
  });
  const remove = useMutation({
    mutationFn: (symbol: string) => api<{ ticker: string }>(`/api/watchlist/${encodeURIComponent(symbol)}`, { method: "DELETE" }),
    onSuccess: async () => {
      await queryClient.invalidateQueries({ queryKey: ["watchlist"] });
    },
  });

  const rows = history.data ?? [];
  const completed = rows.filter((row) => row.status === "completed");
  const failed = rows.filter((row) => row.status === "failed" || row.status === "timed_out" || row.status === "interrupted");

  function onAdd(event: FormEvent) {
    event.preventDefault();
    if (!ticker.trim()) return;
    add.mutate(ticker.trim());
  }

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <h1 className="text-xl font-medium">Overview</h1>
          <p className="mt-1 max-w-3xl text-sm text-[#4d5d6d]">
            Research planning only. Quotes are Yahoo Finance. Ratings are generated by the agent run.
          </p>
        </div>
        <div className="flex flex-wrap items-center gap-2">
          <AuthLine auth={auth.data} />
          <Button type="button" onClick={() => navigate("/research")}>New research</Button>
        </div>
      </div>
      <div className="grid gap-4 xl:grid-cols-5">
        <div className="xl:col-span-3">
          <Panel title="Watchlist" action={<span className="font-mono text-[10px] text-[#6b7c8d]">YFINANCE</span>}>
            <form onSubmit={onAdd} className="mb-3 flex gap-2">
              <Input aria-label="Add ticker" value={ticker} onChange={(event) => setTicker(event.target.value.toUpperCase())} placeholder="Add ticker" className="font-mono uppercase" />
              <Button type="submit" variant="outline" disabled={add.isPending || !ticker.trim()}>Add</Button>
            </form>
            {add.isError && <p className="mb-2 text-xs text-[#b42334]">{add.error.message}</p>}
            <WatchTable items={watchlist.data?.items ?? []} loading={watchlist.isLoading} error={watchlist.error} onRemove={(symbol) => remove.mutate(symbol)} />
          </Panel>
        </div>
        <div className="space-y-4 xl:col-span-2">
          <Panel title="Active research">
            {active.isLoading && <p className="text-sm text-[#4d5d6d]">Loading activity.</p>}
            {active.error && <p className="text-sm text-[#b42334]">{active.error.message}</p>}
            {!active.isLoading && (active.data ?? []).length === 0 && <p className="text-sm text-[#4d5d6d]">No analysis is running.</p>}
            <ul className="space-y-2">
              {(active.data ?? []).map((row) => (
                <li key={row.id}>
                  <Link to={`/research/${row.id}`} className="flex items-center justify-between gap-3 text-sm">
                    <span className="font-mono">{row.ticker}</span>
                    <span className="text-[#8a5a00]">{row.phase.replaceAll("_", " ")}</span>
                  </Link>
                </li>
              ))}
            </ul>
          </Panel>
          <Panel title="Recently completed">
            <HistoryList rows={completed} empty="No completed research yet." />
          </Panel>
          <Panel title="Recently failed">
            <HistoryList rows={failed.filter((row) => !ACTIVE.has(row.status))} empty="No failed research." />
          </Panel>
        </div>
      </div>
    </div>
  );
}

function AuthLine({ auth }: { auth: ConfigOptions | undefined }) {
  if (!auth) return <Badge>Checking configuration</Badge>;
  const provider = auth.providers.find((item) => item.id === "openai");
  if (!provider) return null;
  if (!provider.auth_message) return <Badge>OpenAI key configured · not verified</Badge>;
  return <p className="max-w-sm text-xs text-[#8a5a00]">{provider.auth_message}</p>;
}

function WatchTable({
  items,
  loading,
  error,
  onRemove,
}: {
  items: WatchlistResponse["items"];
  loading: boolean;
  error: Error | null;
  onRemove: (ticker: string) => void;
}) {
  if (loading) return <p className="text-sm text-[#4d5d6d]">Loading quotes.</p>;
  if (error) return <p className="text-sm text-[#b42334]">{error.message}</p>;
  if (items.length === 0) return <p className="text-sm text-[#4d5d6d]">The watchlist is empty. Add a ticker above.</p>;
  return (
    <div className="overflow-x-auto">
      <table className="w-full text-left text-sm">
        <thead className="text-[11px] tracking-wide text-[#6b7c8d] uppercase">
          <tr>
            <th className="py-1 pr-3 font-medium">Ticker</th>
            <th className="py-1 pr-3 font-medium">Close</th>
            <th className="py-1 pr-3 font-medium">Bar</th>
            <th className="py-1 font-medium">Quality</th>
          </tr>
        </thead>
        <tbody>
          {items.map((item) => (
            <tr key={item.ticker} className="border-t border-[#d5dee6]">
              <td className="py-2 pr-3 font-mono">
                <Link to={`/research?ticker=${encodeURIComponent(item.ticker)}`}>{item.ticker}</Link>
              </td>
              <td className="py-2 pr-3 font-mono">
                {item.ok ? formatNumber(item.price ?? null) : <span className="text-[#b42334]">{item.error ?? "No price"}</span>}
              </td>
              <td className="py-2 pr-3 text-[#4d5d6d]">{item.bar_date ?? "Unknown"}</td>
              <td className="py-2 text-right">
                <span className="mr-2 text-xs text-[#4d5d6d]">{item.ok ? "Quote loaded" : "Quote missing"}</span>
                <Button variant="ghost" size="sm" onClick={() => onRemove(item.ticker)}>Remove</Button>
              </td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

function HistoryList({ rows, empty }: { rows: AnalysisRecord[]; empty: string }) {
  if (rows.length === 0) return <p className="text-sm text-[#4d5d6d]">{empty}</p>;
  return (
    <ul className="space-y-2">
      {rows.slice(0, 6).map((row) => (
        <li key={row.id} className="text-sm">
          <Link to={`/research/${row.id}`} className="font-mono">{row.ticker}</Link>
          <div className="text-xs text-[#4d5d6d]">
            {row.analysis_date} · {row.status.replaceAll("_", " ")} · {quality(row)} · {row.rating === "REVIEW" ? "No readable rating" : row.rating ?? "No rating"}
          </div>
          <div className="text-[11px] text-[#6b7c8d]">{formatWhen(row.created_at)}</div>
        </li>
      ))}
    </ul>
  );
}

function quality(row: AnalysisRecord): string {
  const sources = row.data_sources as { memory_error?: string | null; report_error?: string | null; market?: { status?: string } };
  if (sources?.memory_error || sources?.report_error) return "Partial tools";
  if (sources?.market?.status === "unavailable") return "Market data missing";
  if (row.status === "completed") return "Saved";
  return "See run";
}
